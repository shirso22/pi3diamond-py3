    # Data Acquisition
    def generate_sequence(self):
        """ We generate a Deer frequency sequence conditional on the user input.
        We either create a Hahn Echo sequence with an rf pulse after the NV pi pulse with variable
        delay, or we use a XY8 decoupling sequence with rf pulses of variable delay after the pi
        pulses.
        :return: Sequence string
        """
        # Values for the NV center
        mw_tau = self.mw_tau
        decay_init = self.decay_init
        laser = self.laser
        mw_x_t_pi2 = self.mw_x_t_pi2
        mw_x_t_pi = self.mw_x_t_pi
        mw_y_t_pi = self.mw_y_t_pi
        n = self.decoupling_order

        # Defining the RF sequence:
        rf_t_pi = self.rf_t_pi
        rf_pulse_delay = float(self.rf_pulse_delay)

        sequence_rf = []
        sequence_nv = []

        if n == 0:
            # Do a simple Hahn Sequence
            if rf_pulse_delay != 0.0:
                sequence_rf += [([], decay_init + mw_x_t_pi2 + mw_tau * 0.5 + mw_x_t_pi +
                                 rf_pulse_delay),
                                (['rf'], rf_t_pi),
                                ([], mw_tau * 0.5 - rf_pulse_delay - rf_t_pi +
                                 mw_x_t_pi2 + laser)]
                sequence_nv += [([], decay_init), (['mw'], mw_x_t_pi2), ([], mw_tau * 0.5),
                                (['mw'], mw_x_t_pi),
                                ([], mw_tau * 0.5), (['mw'], mw_x_t_pi2),
                                (['detect', 'aom'], laser)]
            else:
                sequence_rf += [([], decay_init + mw_x_t_pi2 + mw_tau * 0.5),
                                (['rf'], rf_t_pi),
                                ([], mw_tau * 0.5 - rf_t_pi + mw_x_t_pi + mw_x_t_pi2 +
                                 laser)]
                sequence_nv += [([], decay_init), (['mw'], mw_x_t_pi2), ([], mw_tau * 0.5),
                                (['mw'], mw_x_t_pi),
                                ([], mw_tau * 0.5), (['mw'], mw_x_t_pi2),
                                (['detect', 'aom'], laser)]

            sequence_nv += [(['sequence'], 100)]
            sequence_rf += [(['sequence'], 100)]

            # Removing zeros from sequences:
            sequence_nv = sequence_remove_zeros(sequence_nv)
            sequence_rf = sequence_remove_zeros(sequence_rf)

            # Mixing both MW and RF sequences:
            sequence = sequence_union(sequence_rf, sequence_nv)
        else:
            # Do a XY8 Sequence with rf in between of variable delay
            # t is the time between the infinitely short xy8 pulses
            t = mw_tau / (8. * n)
            # This function gives the correct tau for the approximation of infinitely short NV pulses
            t_bar = lambda tau, p1, p2=0., p3=0., p4=0.: tau - (p1 / 2.) - (p2 / 2.) - p3 - p4
            # check if the NV interpulse delay is long enough to fit the rf pulse in
            if t_bar(t, mw_x_t_pi, mw_x_t_pi, rf_pulse_delay, rf_t_pi) < 0 or t_bar(t, mw_y_t_pi,
                                                                                    mw_y_t_pi,
                                                                                    rf_pulse_delay,
                                                                                    rf_t_pi) < 0:
                raise IOError(
                    'The delay between pulses is too short. It has to be larger than the duration '
                    'of a pulse')
            # Build the parts of the sequence
            xy_8_rf_part = []
            init = [(['detect', 'aom'], laser), ([], decay_init)]
            xy_8_rf_part += [(['mw_x'], mw_x_t_pi), ([], rf_pulse_delay), (['rf'], rf_t_pi),
                             ([], t_bar(t, mw_x_t_pi, mw_y_t_pi, rf_pulse_delay, rf_t_pi))]
            xy_8_rf_part += [(['mw_y'], mw_y_t_pi), ([], rf_pulse_delay), (['rf'], rf_t_pi),
                             ([], t_bar(t, mw_x_t_pi, mw_y_t_pi, rf_pulse_delay, rf_t_pi))]
            xy_8_rf_part += [(['mw_x'], mw_x_t_pi), ([], rf_pulse_delay), (['rf'], rf_t_pi),
                             ([], t_bar(t, mw_x_t_pi, mw_y_t_pi, rf_pulse_delay, rf_t_pi))]
            xy_8_rf_part += [(['mw_y'], mw_y_t_pi), ([], rf_pulse_delay), (['rf'], rf_t_pi),
                             ([], t_bar(t, mw_y_t_pi, mw_y_t_pi, rf_pulse_delay, rf_t_pi))]
            xy_8_rf_part += [(['mw_y'], mw_y_t_pi), ([], rf_pulse_delay), (['rf'], rf_t_pi),
                             ([], t_bar(t, mw_x_t_pi, mw_y_t_pi, rf_pulse_delay, rf_t_pi))]
            xy_8_rf_part += [(['mw_x'], mw_x_t_pi), ([], rf_pulse_delay), (['rf'], rf_t_pi),
                             ([], t_bar(t, mw_x_t_pi, mw_y_t_pi, rf_pulse_delay, rf_t_pi))]
            xy_8_rf_part += [(['mw_y'], mw_y_t_pi), ([], rf_pulse_delay), (['rf'], rf_t_pi),
                             ([], t_bar(t, mw_x_t_pi, mw_y_t_pi, rf_pulse_delay, rf_t_pi))]
            xy_8_rf_part += [(['mw_x'], mw_x_t_pi), ([], rf_pulse_delay), (['rf'], rf_t_pi)]
            start = [(['mw_x'], mw_x_t_pi2), ([], t_bar(t / 2., mw_x_t_pi))]
            end_pi2 = [([], t_bar(t / 2., mw_x_t_pi, rf_pulse_delay, rf_t_pi)),
                       (['mw_x'], mw_x_t_pi2)]

            sequence = start + (
                    (n - 1) * (
                    xy_8_rf_part + [([], t_bar(t, mw_x_t_pi, mw_x_t_pi, rf_pulse_delay, rf_t_pi))])) \
                       + xy_8_rf_part + end_pi2 + init

        sequence = 100 * sequence
        return sequence

    def apply_parameters(self):
        """Apply the current parameters and decide whether to keep previous data.

        Overwritten from measurements.pulsed to include changes on the frequency array
        :return: void
        """
        frequency = np.arange(self.rf_begin, self.rf_end, self.rf_delta)

        if not self.keep_data or np.any(frequency != self.frequency):
            self.frequency = frequency

        Pulsed.apply_parameters(self)

    def start_up(self):
        self.pulse_generator.Night()
        self.microwave.setOutput(self.mw_power, self.mw_frequency)
        self.rf.setPower(self.rf_power)

    def shut_down(self):
        self.pulse_generator.Light()
        self.microwave.setOutput(None, self.mw_frequency)
        self.rf.setOutput(None, self.rf_begin)

    # Override regular pulsed._run here to account for frequency sweep instead of tau sweep
    def _run(self):
        """Main measurement loop of a deer sweep

        Sweep the Frequency of the SMIQ and simultaneously switch between bins in the
        TimeTagger.PulsedExtTrig class mitigated via a nidaq.SquareWave.
        :return: Nothing. This loop will just run until it is ended!
        """

        try:  # try to run the acquisition from start_up to shut_down
            self.state = 'run'
            self.apply_parameters()
            logging.getLogger().debug('Apply parameters done.')

            if self.run_time >= self.stop_time:
                logging.getLogger().debug('Runtime larger than stop_time. Returning')
                self.state = 'done'
                return

            self.start_up()
            logging.getLogger().debug('Start up done.')
            self.pulse_generator.Night()
            if self.AFM:  # global_vars.pixel_count == 0:
                pulsed_0 = self.time_tagger.PulsedAFM(self.n_bins,
                                                      int(np.round(self.bin_width * 1000)),
                                                      self.frequency.shape[0],
                                                      self.channel_apd_0, self.channel_apd_1,
                                                      global_vars.pixel_count * 2,
                                                      global_vars.line_count, self.win_low,
                                                      self.win_high, self.ref_low, self.ref_high,
                                                      self.channel_detect,
                                                      self.channel_sequence, self.pixel_trigger,
                                                      self.line_trigger)
                # if self.channel_apd_1 > -1:
                # pulsed_1 = self.time_tagger.Pulsed(self.n_bins, int(np.round(self.bin_width*1000)), self.n_laser, self.channel_apd_1, self.channel_detect, self.channel_sequence)
            else:
                # self.AFM = False
                pulsed_0 = self.time_tagger.PulsedExtTrig(self.n_bins,
                                                          int(np.round(self.bin_width * 1000)),
                                                          self.frequency.shape[0],
                                                          self.channel_apd_0, self.channel_apd_1,
                                                          self.channel_detect,
                                                          self.channel_sequence,
                                                          self.bin_trigger_channel,
                                                          self.trig_1_channel,
                                                          self.trig_2_channel,
                                                          self.dual_sequence)
            # Generate the TTL pulsetrain object that triggers frequency bins.
            self.squarewave = SquareWave('/dev1/ctr0, /dev1/ctr1', self.frequency.shape[0],
                                         self.seconds_per_point, duty_cycle=0.1)
            # prepare hardware for sweeps
            self.rf.setPower(self.rf_power)
            self.rf.initSweep(self.frequency, self.rf_power * np.ones(self.frequency.shape))
            self.pulse_generator.Sequence(self.sequence)
            self.pulse_generator.checkUnderflow()
            logging.getLogger().debug('Time tagger set and pulse_generator checked.')
            logging.getLogger().debug(
                'Run time<stop_time ' + str(
                    self.run_time < self.stop_time) + ' and ss<stop_counts ' + str(
                    any(self.spin_state < self.stop_counts)) + ' -> STARTING')

            while self.run_time < self.stop_time and any(self.spin_state < self.stop_counts):
                start_time = time.time()
                self.thread.stop_request.wait(0.1)
                if self.thread.stop_request.is_set():
                    logging.getLogger().debug('Caught stop signal. Exiting.')
                    break
                if self.pulse_generator.checkUnderflow():
                    raise RuntimeError('Underflow in pulse generator.')
                pulsed_0.resetSweep()
                self.rf.resetListPos()
                self.squarewave.output()
                if self.old_count_data.shape == pulsed_0.getData().shape:
                    self.count_data = self.old_count_data + pulsed_0.getData()
                else:
                    self.count_data = pulsed_0.getData()
                self.run_time += time.time() - start_time
                logging.getLogger().debug(
                    'RT<ST ' + str(self.run_time < self.stop_time) + ' and SS<SC ' + str(
                        any(self.spin_state < self.stop_counts)) + ' - SC =' + str(
                        self.stop_counts))

            if self.run_time < self.stop_time:
                self.state = 'idle'
            else:
                try:
                    self.save(self.filename)
                except:
                    logging.getLogger().exception('Failed to save the data to file.')
                self.state = 'done'
            del pulsed_0

            self.shut_down()
            self.pulse_generator.Light()

        except:  # if anything fails, log the exception and set the state
            logging.getLogger().exception('Something went wrong in pulsed loop.')
            self.state = 'error'

    # fitting
    def _update_fit(self):
        if self.perform_fit:
            N = self.number_of_resonances
            if N != 'auto':
                N = int(N)
            try:
                p, dp = fit_odmr(self.frequency, self.spin_state, threshold=self.threshold * 0.01,
                                 number_of_peaks=N)
            except Exception:
                logging.getLogger().debug('ODMR fit failed.', exc_info=True)
                p = np.nan * np.empty(4)
        else:
            p = np.nan * np.empty(4)
        self.fit_parameters = p
        self.fit_frequencies = p[1::3]
        self.fit_line_width = p[2::3]
        N = len(p) // 3
        contrast = np.empty(N)
        c = p[0]
        pp = p[1:].reshape((N, 3))
        for i, pi in enumerate(pp):
            a = pi[2]
            g = pi[1]
            A = np.abs(a / (np.pi * g))
            if a > 0:
                contrast[i] = 100 * A / (A + c)
            else:
                contrast[i] = 100 * A / c
        self.fit_contrast = contrast
        if len(self.fit_frequencies) == 2 and self.calculate_center:
            self.center = abs(self.fit_frequencies[0] + self.fit_frequencies[1]) / 2.
        else:
            self.center = np.nan

